-- =============================================
-- Softtek - Amenidades: masajes y recuperacion fisica
-- Motor: MySQL 8
-- Solo lectura: el procedimiento unicamente consulta estadisticas
-- =============================================

SET NAMES utf8mb4;

DROP DATABASE IF EXISTS Softtek_Amenidades;
CREATE DATABASE Softtek_Amenidades CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE Softtek_Amenidades;

-- ---------------------------------------------
-- 1. Tablas
-- ---------------------------------------------
CREATE TABLE usuarios (
    id_usuario INT AUTO_INCREMENT PRIMARY KEY,
    nombre     VARCHAR(60) NOT NULL,
    apellido   VARCHAR(60) NOT NULL,
    area       VARCHAR(40) NOT NULL
);

-- Cada fila es una visita: las veces que aparece un usuario = las veces que fue
CREATE TABLE registro_masajes (
    id_registro INT AUTO_INCREMENT PRIMARY KEY,
    id_usuario  INT  NOT NULL,
    fecha       DATE NOT NULL,
    hora        TIME NOT NULL,
    UNIQUE (id_usuario, fecha),   -- una visita por persona al dia
    FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
);

CREATE TABLE registro_recuperacion (
    id_registro INT AUTO_INCREMENT PRIMARY KEY,
    id_usuario  INT  NOT NULL,
    fecha       DATE NOT NULL,
    hora        TIME NOT NULL,
    UNIQUE (id_usuario, fecha),
    FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
);

DELIMITER //

-- ---------------------------------------------
-- 2. Funciones
-- ---------------------------------------------

-- DAYOFWEEK: 1 = domingo, 2 = lunes, 3 = martes, 4 = miercoles, 5 = jueves
CREATE FUNCTION fn_es_martes_o_jueves(p_fecha DATE)
RETURNS BOOLEAN
DETERMINISTIC
BEGIN
    RETURN DAYOFWEEK(p_fecha) IN (3, 5);
END //

CREATE FUNCTION fn_nombre_dia(p_fecha DATE)
RETURNS VARCHAR(10)
DETERMINISTIC
BEGIN
    RETURN CASE DAYOFWEEK(p_fecha)
        WHEN 3 THEN 'Martes'
        WHEN 5 THEN 'Jueves'
        ELSE 'Otro'
    END;
END //

-- Porcentaje con 2 decimales; si el total es 0 regresa 0
CREATE FUNCTION fn_porcentaje(p_parte DECIMAL(10,2), p_total DECIMAL(10,2))
RETURNS DECIMAL(5,2)
DETERMINISTIC
BEGIN
    IF p_total IS NULL OR p_total = 0 THEN
        RETURN 0;
    END IF;
    RETURN ROUND(p_parte * 100 / p_total, 2);
END //

-- Promedio de visitas por usuario en una semana
CREATE FUNCTION fn_promedio_semanal(p_visitas INT, p_usuarios INT, p_semanas INT)
RETURNS DECIMAL(6,2)
DETERMINISTIC
BEGIN
    IF p_usuarios IS NULL OR p_usuarios = 0 OR p_semanas IS NULL OR p_semanas = 0 THEN
        RETURN 0;
    END IF;
    RETURN ROUND(p_visitas / (p_usuarios * p_semanas), 2);
END //

-- Discrimina a que actividad fue mas un usuario
CREATE FUNCTION fn_actividad_favorita(p_masajes INT, p_recuperacion INT)
RETURNS VARCHAR(20)
DETERMINISTIC
BEGIN
    RETURN CASE
        WHEN p_masajes = 0 AND p_recuperacion = 0 THEN 'Ninguna'
        WHEN p_masajes > p_recuperacion           THEN 'Masajes'
        WHEN p_recuperacion > p_masajes           THEN 'Recuperación física'
        ELSE 'Empate'
    END;
END //

-- ---------------------------------------------
-- 3. Triggers (solo martes y jueves, de 08:00 a 18:00)
-- ---------------------------------------------
CREATE TRIGGER trg_masajes_before_insert
BEFORE INSERT ON registro_masajes
FOR EACH ROW
BEGIN
    IF NOT fn_es_martes_o_jueves(NEW.fecha) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Los masajes solo son martes y jueves';
    ELSEIF NEW.hora NOT BETWEEN '08:00:00' AND '18:00:00' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'El horario es de 08:00 a 18:00';
    END IF;
END //

CREATE TRIGGER trg_recuperacion_before_insert
BEFORE INSERT ON registro_recuperacion
FOR EACH ROW
BEGIN
    IF NOT fn_es_martes_o_jueves(NEW.fecha) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'La recuperacion fisica solo es martes y jueves';
    ELSEIF NEW.hora NOT BETWEEN '08:00:00' AND '18:00:00' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'El horario es de 08:00 a 18:00';
    END IF;
END //

DELIMITER ;

-- ---------------------------------------------
-- 4. Vistas
-- ---------------------------------------------

-- Una fila por usuario con cuantas veces fue a cada actividad.
-- LEFT JOIN: aparecen los 200 usuarios aunque nunca hayan ido (veces = 0).
-- Cada tabla se cuenta en una subconsulta ANTES del join; si se unieran las dos
-- tablas de registro directo, las visitas se multiplicarian (masajes x recuperacion).
CREATE VIEW vw_asistencia_usuario AS
SELECT u.id_usuario,
       CONCAT(u.nombre, ' ', u.apellido)            AS nombre_completo,
       u.area,
       COALESCE(m.veces, 0)                          AS veces_masajes,
       COALESCE(r.veces, 0)                          AS veces_recuperacion,
       COALESCE(m.veces, 0) + COALESCE(r.veces, 0)   AS total_visitas,
       fn_actividad_favorita(COALESCE(m.veces, 0), COALESCE(r.veces, 0)) AS actividad_favorita
FROM usuarios u
LEFT JOIN (SELECT id_usuario, COUNT(*) AS veces
           FROM registro_masajes
           GROUP BY id_usuario) m ON m.id_usuario = u.id_usuario
LEFT JOIN (SELECT id_usuario, COUNT(*) AS veces
           FROM registro_recuperacion
           GROUP BY id_usuario) r ON r.id_usuario = u.id_usuario;

-- Todas las visitas de ambas actividades en una sola lista
CREATE VIEW vw_visitas AS
SELECT id_usuario, fecha, hora, 'Masajes' AS actividad FROM registro_masajes
UNION ALL
SELECT id_usuario, fecha, hora, 'Recuperación física' FROM registro_recuperacion;

DELIMITER //

-- ---------------------------------------------
-- 5. Procedimiento almacenado (solo lectura)
-- ---------------------------------------------

-- p_accion:
--   'RESUMEN'   totales y porcentajes generales (1 fila)
--   'USUARIOS'  los 200 usuarios con sus visitas y actividad favorita
--   'TOP'       quien fue mas a cada actividad (p_limite posiciones, empates incluidos)
--   'POR_DIA'   visitas por dia (martes / jueves) y actividad
--   'POR_SEMANA' visitas de cada semana del periodo
--   'POR_HORA'  visitas por hora y actividad
--   'POR_AREA'  visitas y porcentaje de asistencia por area
CREATE PROCEDURE sp_estadisticas(
    IN p_accion VARCHAR(20),
    IN p_limite INT
)
BEGIN
    -- Semanas con actividad (YEARWEEK con modo 1: la semana empieza en lunes)
    DECLARE v_semanas INT;
    SET v_semanas = (SELECT COUNT(DISTINCT YEARWEEK(fecha, 1)) FROM vw_visitas);

    CASE p_accion
        WHEN 'RESUMEN' THEN
            -- (condicion) vale 1 o 0, asi SUM(condicion) cuenta cuantos la cumplen
            SELECT COUNT(*)                                              AS total_usuarios,
                   SUM(veces_masajes > 0)                                AS usuarios_masajes,
                   SUM(veces_recuperacion > 0)                           AS usuarios_recuperacion,
                   SUM(veces_masajes > 0 AND veces_recuperacion > 0)     AS usuarios_ambas,
                   SUM(veces_masajes > 0 AND veces_recuperacion = 0)     AS usuarios_solo_masajes,
                   SUM(veces_recuperacion > 0 AND veces_masajes = 0)     AS usuarios_solo_recuperacion,
                   SUM(total_visitas > 0)                                AS usuarios_asistieron,
                   SUM(total_visitas = 0)                                AS usuarios_ninguna,
                   SUM(veces_masajes)                                    AS visitas_masajes,
                   SUM(veces_recuperacion)                               AS visitas_recuperacion,
                   SUM(total_visitas)                                    AS total_visitas,
                   fn_porcentaje(SUM(veces_masajes > 0), COUNT(*))       AS pct_usuarios_masajes,
                   fn_porcentaje(SUM(veces_recuperacion > 0), COUNT(*))  AS pct_usuarios_recuperacion,
                   fn_porcentaje(SUM(veces_masajes > 0 AND veces_recuperacion > 0), COUNT(*)) AS pct_usuarios_ambas,
                   fn_porcentaje(SUM(veces_masajes > 0 AND veces_recuperacion = 0), COUNT(*)) AS pct_usuarios_solo_masajes,
                   fn_porcentaje(SUM(veces_recuperacion > 0 AND veces_masajes = 0), COUNT(*)) AS pct_usuarios_solo_recuperacion,
                   fn_porcentaje(SUM(total_visitas > 0), COUNT(*))       AS pct_asistencia_total,
                   fn_porcentaje(SUM(veces_masajes), SUM(total_visitas)) AS pct_visitas_masajes,
                   fn_porcentaje(SUM(veces_recuperacion), SUM(total_visitas)) AS pct_visitas_recuperacion,
                   v_semanas                                             AS semanas,
                   fn_promedio_semanal(SUM(veces_masajes), COUNT(*), v_semanas)      AS prom_semanal_masajes,
                   fn_promedio_semanal(SUM(veces_recuperacion), COUNT(*), v_semanas) AS prom_semanal_recuperacion,
                   fn_promedio_semanal(SUM(total_visitas), COUNT(*), v_semanas)      AS prom_semanal_total
            FROM vw_asistencia_usuario;

        WHEN 'USUARIOS' THEN
            SELECT * FROM vw_asistencia_usuario
            ORDER BY total_visitas DESC, nombre_completo;

        -- INNER JOIN: solo entran los usuarios que si fueron a la actividad.
        -- RANK() da la misma posicion a los empates.
        WHEN 'TOP' THEN
            SELECT * FROM (
                SELECT 'Masajes' AS actividad, u.id_usuario,
                       CONCAT(u.nombre, ' ', u.apellido) AS nombre_completo, u.area,
                       COUNT(*) AS veces,
                       RANK() OVER (ORDER BY COUNT(*) DESC) AS posicion
                FROM usuarios u
                INNER JOIN registro_masajes m ON m.id_usuario = u.id_usuario
                GROUP BY u.id_usuario

                UNION ALL

                SELECT 'Recuperación física', u.id_usuario,
                       CONCAT(u.nombre, ' ', u.apellido), u.area,
                       COUNT(*),
                       RANK() OVER (ORDER BY COUNT(*) DESC)
                FROM usuarios u
                INNER JOIN registro_recuperacion r ON r.id_usuario = u.id_usuario
                GROUP BY u.id_usuario
            ) AS t
            WHERE posicion <= IFNULL(p_limite, 5)
            ORDER BY actividad, posicion, nombre_completo;

        WHEN 'POR_DIA' THEN
            SELECT fn_nombre_dia(fecha)                   AS dia,
                   SUM(actividad = 'Masajes')             AS masajes,
                   SUM(actividad = 'Recuperación física') AS recuperacion,
                   COUNT(*)                               AS total
            FROM vw_visitas
            GROUP BY dia
            ORDER BY MIN(DAYOFWEEK(fecha));

        WHEN 'POR_SEMANA' THEN
            -- La fecha se da ya formateada para que no la mueva la zona horaria
            SELECT YEARWEEK(fecha, 1)                     AS semana,
                   DATE_FORMAT(MIN(fecha), '%d/%m')       AS inicio,
                   SUM(actividad = 'Masajes')             AS masajes,
                   SUM(actividad = 'Recuperación física') AS recuperacion,
                   COUNT(*)                               AS total,
                   COUNT(DISTINCT fecha)                  AS dias
            FROM vw_visitas
            GROUP BY semana
            ORDER BY semana;

        WHEN 'POR_HORA' THEN
            SELECT HOUR(hora)                             AS hora_del_dia,
                   SUM(actividad = 'Masajes')             AS masajes,
                   SUM(actividad = 'Recuperación física') AS recuperacion,
                   COUNT(*)                               AS total
            FROM vw_visitas
            GROUP BY HOUR(hora)
            ORDER BY hora_del_dia;

        WHEN 'TENDENCIAS' THEN
            -- Primera mitad del periodo contra la segunda, para ver que area subio o bajo
            SELECT u.area,
                   SUM(v.fecha <  '2026-04-01')                AS visitas_inicio,
                   SUM(v.fecha >= '2026-04-01')                AS visitas_fin,
                   SUM(v.actividad = 'Masajes')                AS masajes,
                   SUM(v.actividad = 'Recuperación física')    AS recuperacion,
                   COUNT(*)                                    AS total,
                   (SELECT HOUR(v2.hora)
                    FROM vw_visitas v2
                    INNER JOIN usuarios u2 ON u2.id_usuario = v2.id_usuario
                    WHERE u2.area = u.area
                    GROUP BY HOUR(v2.hora)
                    ORDER BY COUNT(*) DESC, HOUR(v2.hora)
                    LIMIT 1)                                   AS hora_pico
            FROM vw_visitas v
            INNER JOIN usuarios u ON u.id_usuario = v.id_usuario
            GROUP BY u.area
            ORDER BY SUM(v.fecha >= '2026-04-01') - SUM(v.fecha < '2026-04-01') DESC;

        WHEN 'POR_AREA' THEN
            SELECT area,
                   COUNT(*)                                        AS usuarios,
                   SUM(veces_masajes)                              AS visitas_masajes,
                   SUM(veces_recuperacion)                         AS visitas_recuperacion,
                   fn_porcentaje(SUM(total_visitas > 0), COUNT(*)) AS pct_asistencia
            FROM vw_asistencia_usuario
            GROUP BY area
            ORDER BY pct_asistencia DESC, area;

        ELSE
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Accion no valida';
    END CASE;
END //

DELIMITER ;

